"""Generates the bronze layer from the live Postgres schema (FR-F5, DC-4).

Writes two files from information_schema, so bronze always matches the source:

  trino/ddl/bronze.sql            Iceberg tables, partitioned by day(commit_ts)
  flink/sql/bronze/bronze_cdc.sql Flink job: CDC topics (Debezium Avro) -> bronze

Bronze keeps the Debezium envelope as it arrived: dates stay Debezium day
numbers and timestamptz stays an ISO-8601 string. Silver parses them.

    uv run python scripts/gen_bronze.py            # write the files
    uv run python scripts/gen_bronze.py --check    # exit 1 if they are stale
"""

import argparse
import os
import sys
from dataclasses import dataclass
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[1]
TRINO_DDL = ROOT / "trino/ddl/bronze.sql"
FLINK_JOB = ROOT / "flink/sql/bronze/bronze_cdc.sql"
TABLES = ("customers", "cards", "merchants", "sessions", "transactions", "chargebacks")
CHECKPOINT_INTERVAL = "60s"  # also the Iceberg commit interval (FR-F5)


@dataclass(frozen=True)
class Column:
    name: str
    data_type: str
    precision: int | None
    scale: int | None

    def _decimal(self) -> tuple[int, int]:
        if self.precision is None or self.scale is None:
            raise ValueError(f"{self.name}: unbounded numeric is not supported in bronze")
        return self.precision, self.scale

    def flink_type(self) -> str:
        """Type of the field as Debezium's Avro converter writes it."""
        t = self.data_type
        if t == "bigint":
            return "BIGINT"
        if t in ("integer", "smallint", "date"):  # date: Debezium days since epoch
            return "INT"
        if t == "numeric":
            p, s = self._decimal()
            return f"DECIMAL({p}, {s})"
        if t == "double precision":
            return "DOUBLE"
        if t == "boolean":
            return "BOOLEAN"
        if t in ("text", "character", "character varying", "inet", "timestamp with time zone"):
            return "STRING"  # timestamptz: Debezium ZonedTimestamp, ISO-8601 text
        raise ValueError(f"{self.name}: no bronze mapping for Postgres type {t!r}")

    def trino_type(self) -> str:
        return {
            "BIGINT": "bigint",
            "INT": "integer",
            "DOUBLE": "double",
            "BOOLEAN": "boolean",
            "STRING": "varchar",
        }.get(self.flink_type(), self.flink_type().lower().replace(", ", ","))


def load_columns(dsn: str) -> dict[str, list[Column]]:
    with psycopg.connect(dsn) as conn:
        rows = conn.execute(
            "select table_name, column_name, data_type, numeric_precision, numeric_scale "
            "from information_schema.columns where table_schema = 'public' "
            "and table_name = any(%s) order by table_name, ordinal_position",
            (list(TABLES),),
        ).fetchall()
    columns: dict[str, list[Column]] = {t: [] for t in TABLES}
    for table, name, data_type, precision, scale in rows:
        columns[str(table)].append(Column(str(name), str(data_type), precision, scale))
    missing = [t for t, cols in columns.items() if not cols]
    if missing:
        raise SystemExit(f"tables not found in Postgres: {missing} (run make up)")
    return columns


HEADER = "-- Generated by scripts/gen_bronze.py from the Postgres schema. Do not edit by hand.\n"


def trino_ddl(columns: dict[str, list[Column]]) -> str:
    out = [HEADER, "\nCREATE SCHEMA IF NOT EXISTS lake.bronze;\n"]
    for table in TABLES:
        row = ", ".join(f"{c.name} {c.trino_type()}" for c in columns[table])
        out.append(
            f"""
CREATE TABLE IF NOT EXISTS lake.bronze.cdc_{table} (
    op varchar,
    before ROW({row}),
    after ROW({row}),
    commit_ts timestamp(6) with time zone,
    lsn bigint,
    tx_id bigint,
    snapshot varchar,
    connector_ts timestamp(6) with time zone,
    kafka_partition integer,
    kafka_offset bigint,
    kafka_timestamp timestamp(6) with time zone,
    ingested_at timestamp(6) with time zone
)
WITH (format = 'PARQUET', partitioning = ARRAY['day(commit_ts)']);
"""
        )
    return "".join(out)


def flink_job(columns: dict[str, list[Column]]) -> str:
    out = [
        HEADER,
        f"""
-- Bronze sink (FR-F5): append every Debezium change event to lake.bronze.cdc_*.
-- Exactly-once: Kafka offsets and Iceberg commits are both tied to checkpoints.

SET 'pipeline.name' = 'bronze-cdc';
SET 'execution.runtime-mode' = 'streaming';
SET 'execution.checkpointing.interval' = '{CHECKPOINT_INTERVAL}';
SET 'execution.checkpointing.mode' = 'EXACTLY_ONCE';

CREATE CATALOG lake WITH (
    'type' = 'iceberg',
    'catalog-type' = 'rest',
    'uri' = 'http://lakekeeper:8181/catalog',
    'warehouse' = 'lakehouse',
    'io-impl' = 'org.apache.iceberg.aws.s3.S3FileIO',
    's3.endpoint' = 'http://seaweedfs:8333',
    's3.path-style-access' = 'true',
    'client.region' = 'us-east-1'
);
""",
    ]
    for table in TABLES:
        row = ", ".join(f"`{c.name}` {c.flink_type()}" for c in columns[table])
        out.append(
            f"""
CREATE TEMPORARY TABLE kafka_{table} (
    `before` ROW<{row}>,
    `after` ROW<{row}>,
    `source` ROW<`ts_ms` BIGINT, `lsn` BIGINT, `txId` BIGINT, `snapshot` STRING>,
    `op` STRING,
    `ts_ms` BIGINT,
    `kafka_partition` INT METADATA FROM 'partition' VIRTUAL,
    `kafka_offset` BIGINT METADATA FROM 'offset' VIRTUAL,
    `kafka_timestamp` TIMESTAMP_LTZ(3) METADATA FROM 'timestamp' VIRTUAL
) WITH (
    'connector' = 'kafka',
    -- Exact-match pattern with discovery: the source starts even before Debezium has
    -- created the topic (e.g. chargebacks before the first chargeback), then picks it up.
    'topic-pattern' = 'pg\\.public\\.{table}',
    'scan.topic-partition-discovery.interval' = '30s',
    'properties.bootstrap.servers' = 'redpanda:9092',
    'properties.group.id' = 'bronze-cdc',
    'scan.startup.mode' = 'group-offsets',
    'properties.auto.offset.reset' = 'earliest',
    'value.format' = 'avro-confluent',
    'value.avro-confluent.url' = 'http://redpanda:8081'
);
"""
        )
    out.append("\nEXECUTE STATEMENT SET\nBEGIN\n")
    for table in TABLES:
        out.append(
            f"""INSERT INTO lake.bronze.cdc_{table}
SELECT
    `op`, `before`, `after`,
    TO_TIMESTAMP_LTZ(`source`.`ts_ms`, 3) AS commit_ts,
    `source`.`lsn` AS lsn,
    `source`.`txId` AS tx_id,
    `source`.`snapshot` AS snapshot,
    TO_TIMESTAMP_LTZ(`ts_ms`, 3) AS connector_ts,
    `kafka_partition`, `kafka_offset`, `kafka_timestamp`,
    CURRENT_TIMESTAMP AS ingested_at
FROM kafka_{table};
"""
        )
    out.append("END;\n")
    return "".join(out)


def dsn_from_env() -> str:
    values: dict[str, str] = {}
    env_file = ROOT / ".env"
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                values[k.strip()] = v.strip()
    values.update(os.environ)
    return (
        f"host={values.get('POSTGRES_HOST', 'localhost')} "
        f"port={values.get('POSTGRES_PORT', '5432')} "
        f"dbname={values['POSTGRES_DB']} user={values['POSTGRES_USER']} "
        f"password={values.get('POSTGRES_PASSWORD', '')}"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    columns = load_columns(dsn_from_env())
    outputs = {TRINO_DDL: trino_ddl(columns), FLINK_JOB: flink_job(columns)}
    if args.check:
        stale = [
            str(p.relative_to(ROOT))
            for p, text in outputs.items()
            if not p.exists() or p.read_text() != text
        ]
        if stale:
            print(f"stale generated files (run make gen-bronze): {stale}", file=sys.stderr)
            return 1
        print("bronze definitions match the Postgres schema")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
