#!/usr/bin/env bash
# Downloads every jar listed in a jars.txt, verifies it against the repository's
# published .sha1, and prints a lock line with its SHA-256. Image builds then
# verify each download against the lock.
#
#   scripts/lock-jars.sh flink/jars.txt > flink/jars.lock
set -euo pipefail

list="${1:?usage: lock-jars.sh <jars.txt>}"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

sha() {
  local algo="$1" file="$2"
  if command -v "sha${algo}sum" >/dev/null 2>&1; then
    "sha${algo}sum" "$file" | cut -d' ' -f1
  else
    shasum -a "$algo" "$file" | cut -d' ' -f1
  fi
}

echo "# Generated by scripts/lock-jars.sh from ${list}. Do not edit by hand."
echo "# sha256  file  url"
grep -vE '^[[:space:]]*(#|$)' "$list" | while read -r url; do
  name=$(basename "$url")
  curl -fsSL -o "$tmp/$name" "$url"
  published=$(curl -fsSL "${url}.sha1" | cut -c1-40)
  actual=$(sha 1 "$tmp/$name")
  if [[ "$published" != "$actual" ]]; then
    echo "SHA-1 mismatch for ${url}: published ${published}, downloaded ${actual}" >&2
    exit 1
  fi
  printf '%s  %s  %s\n' "$(sha 256 "$tmp/$name")" "$name" "$url"
done
