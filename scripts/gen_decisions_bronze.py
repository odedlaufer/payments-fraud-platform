"""Generates bronze for the decisions topic from the decision record's Avro schema (FR-F5).

    uv run python scripts/gen_decisions_bronze.py          # write the files
    uv run python scripts/gen_decisions_bronze.py --check  # fail if they are out of date

The schema comes from decision_service.decision.avro_schema(), itself generated from
features/definitions.yml, so the Flink job and the Trino table can never drift from what the
decision service writes. Writes trino/ddl/bronze_decisions.sql and
flink/sql/bronze/bronze_decisions.sql. A separate job (bronze-decisions), so bronze-cdc's job
graph and savepoints are untouched.
"""

import argparse
import sys
from pathlib import Path
from typing import Any

from decision_service.decision import avro_schema
from gen_bronze import CATALOG, ROOT

HEADER = (
    "-- Generated by scripts/gen_decisions_bronze.py from the decision record schema. "
    "Do not edit by hand.\n"
)
TRINO_OUT = ROOT / "trino/ddl/bronze_decisions.sql"
FLINK_OUT = ROOT / "flink/sql/bronze/bronze_decisions.sql"
FLINK = {
    "long": "BIGINT",
    "int": "INT",
    "string": "STRING",
    "double": "DOUBLE",
    "boolean": "BOOLEAN",
}
TRINO = {
    "long": "bigint",
    "int": "integer",
    "string": "varchar",
    "double": "double",
    "boolean": "boolean",
}


def _base(avro: Any) -> Any:
    """The non-null branch of a ['null', X] union."""
    if isinstance(avro, list):
        (branch,) = [t for t in avro if t != "null"]
        return branch
    return avro


def flink_type(avro: Any) -> str:
    t = _base(avro)
    if isinstance(t, dict) and t["type"] == "array":
        return f"ARRAY<{flink_type(t['items'])}>"
    if isinstance(t, dict) and t["type"] == "record":
        return (
            "ROW<" + ", ".join(f"`{f['name']}` {flink_type(f['type'])}" for f in t["fields"]) + ">"
        )
    return FLINK[t]


def trino_type(avro: Any) -> str:
    t = _base(avro)
    if isinstance(t, dict) and t["type"] == "array":
        return f"array({trino_type(t['items'])})"
    if isinstance(t, dict) and t["type"] == "record":
        return "row(" + ", ".join(f"{f['name']} {trino_type(f['type'])}" for f in t["fields"]) + ")"
    return TRINO[t]


def trino_ddl(schema: dict[str, Any]) -> str:
    cols = ",\n".join(f"    {f['name']} {trino_type(f['type'])}" for f in schema["fields"])
    return f"""{HEADER}
CREATE SCHEMA IF NOT EXISTS lake.bronze;

CREATE TABLE IF NOT EXISTS lake.bronze.decisions (
{cols},
    decided_at timestamp(6) with time zone,
    kafka_partition integer,
    kafka_offset bigint,
    kafka_timestamp timestamp(6) with time zone,
    ingested_at timestamp(6) with time zone
)
WITH (format = 'PARQUET', partitioning = ARRAY['day(decided_at)']);
"""


def flink_job(schema: dict[str, Any]) -> str:
    cols = ",\n".join(f"    `{f['name']}` {flink_type(f['type'])}" for f in schema["fields"])
    names = ", ".join(f"`{f['name']}`" for f in schema["fields"])
    return f"""{HEADER}
-- Bronze sink for the decisions topic (FR-F5): one row per decision, exactly once, with the
-- logged feature snapshot that parity compares with the offline recomputation (FR-PAR2).

SET 'pipeline.name' = 'bronze-decisions';
SET 'execution.runtime-mode' = 'streaming';
SET 'execution.checkpointing.mode' = 'EXACTLY_ONCE';
{CATALOG}
CREATE TEMPORARY TABLE kafka_decisions (
{cols},
    `kafka_partition` INT METADATA FROM 'partition' VIRTUAL,
    `kafka_offset` BIGINT METADATA FROM 'offset' VIRTUAL,
    `kafka_timestamp` TIMESTAMP_LTZ(3) METADATA FROM 'timestamp' VIRTUAL
) WITH (
    'connector' = 'kafka',
    'topic' = 'decisions',
    'properties.bootstrap.servers' = 'redpanda:9092',
    'properties.group.id' = 'bronze-decisions',
    'scan.startup.mode' = 'group-offsets',
    'properties.auto.offset.reset' = 'earliest',
    'value.format' = 'avro-confluent',
    'value.avro-confluent.url' = 'http://redpanda:8081'
);

INSERT INTO lake.bronze.decisions
SELECT
    {names},
    TO_TIMESTAMP_LTZ(`decided_ms`, 3) AS decided_at,
    `kafka_partition`, `kafka_offset`, `kafka_timestamp`,
    CURRENT_TIMESTAMP AS ingested_at
FROM kafka_decisions;
"""


def outputs() -> dict[Path, str]:
    schema = avro_schema()
    return {TRINO_OUT: trino_ddl(schema), FLINK_OUT: flink_job(schema)}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = [p for p, text in outputs().items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run make gen-decisions-bronze")
        if not stale:
            print("decisions bronze definitions match the decision record schema")
        return 1 if stale else 0
    for p, text in outputs().items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
