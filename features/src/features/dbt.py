"""Generates the dbt offline features model from the definitions (ADR-003, FR-PAR1).

The fourth implementation of features/definitions.yml, after the reference, the Flink job
and the on-demand customer features: every feature for every transaction, as of its event
time, from the lake alone. Generic over feature kinds, like the Flink generator, so a new
feature of an existing kind needs no new SQL. Semantics follow features.reference exactly:

- times are epoch milliseconds, truncated; windows are inclusive [t - w, t] and include
  the transaction itself (ties included);
- "prior mean" excludes only the transaction itself, not others at the same millisecond;
- the previous card-present transaction is the latest by event time, ties broken by arrival
  order: the offset of the transaction's creation event on its CDC topic;
- sums are quantized to cents; a reversal counts from when it happened (status_event_ts);
- customer features: a device's first sighting over all sessions; profile changes from
  consecutive CDC events of the customer, in topic order.
"""

from dataclasses import dataclass

from features.flink import EARTH_RADIUS_KM
from features.model import Definitions, Feature

HEADER = (
    "{# Generated by `uv run features dbt` from features/definitions.yml. "
    "Do not edit by hand. #}\n"
)


def window_ms(f: Feature) -> int:
    delta = f.window_delta
    assert delta is not None, f.name
    return int(delta.total_seconds() * 1000)


def epoch_ms(column: str) -> str:
    return f"{{{{ epoch_ms('{column}') }}}}"


@dataclass(frozen=True)
class OfflineModel:
    defs: Definitions

    def by_kind(self, entity: str, *kinds: str) -> list[Feature]:
        return [f for f in self.defs.for_entity(entity) if f.kind in kinds]

    # ------------------------------------------------------------------ pieces

    def base(self) -> list[str]:
        return [
            "created as (\n"
            "    -- arrival order: the offset of each transaction's creation event\n"
            "    select transaction_id, min(_kafka_offset) as arrival\n"
            "    from {{ ref('stg_cdc__transactions') }}\n"
            "    where _op in ('c', 'r')\n"
            "    group by transaction_id\n"
            ")",
            "txn as (\n"
            "    select\n"
            "        t.transaction_id, t.card_id, t.merchant_id, t.session_id, t.amount,\n"
            "        t.channel, t.lat, t.lon, t.status, c.arrival,\n"
            f"        {epoch_ms('t.event_ts')} as event_ms,\n"
            f"        {epoch_ms('t.status_event_ts')} as status_ms\n"
            "    from {{ ref('transactions_current') }} as t\n"
            "    inner join created as c on t.transaction_id = c.transaction_id\n"
            "    where not t.is_deleted\n"
            ")",
        ]

    def card_windows(self) -> list[str]:
        windowed = self.by_kind(
            "card", "window_count", "window_sum", "window_count_distinct", "ratio_to_prior_mean"
        )
        if not windowed:
            return []
        widest = max(window_ms(f) for f in windowed)
        cols = []
        for f in windowed:
            w = window_ms(f)
            if f.kind == "window_count":
                cols.append(f"count_if(age_ms <= {w}) as {f.name}")
            elif f.kind == "window_sum":
                cols.append(
                    f"cast(sum(case when age_ms <= {w} then o_{f.field} else 0 end) "
                    f"as {f.dtype}) as {f.name}"
                )
            elif f.kind == "window_count_distinct":
                cols.append(
                    f"count(distinct case when age_ms <= {w} then o_{f.field} end) as {f.name}"
                )
            else:  # ratio_to_prior_mean: mean over the window, excluding only this transaction
                cols.append(
                    f"avg(case when age_ms <= {w} and other_id != transaction_id "
                    f"then cast(o_{f.field} as double) end) as {f.name}__mean"
                )
        fields = sorted({str(f.field) for f in windowed if f.field})
        others = "".join(f", o.{x} as o_{x}" for x in fields)
        select = ",\n        ".join(cols)
        return [
            "card_pairs as (\n"
            f"    select t.transaction_id, o.transaction_id as other_id{others},\n"
            "        t.event_ms - o.event_ms as age_ms\n"
            "    from txn as t\n"
            "    inner join txn as o\n"
            f"        on t.card_id = o.card_id and o.event_ms between t.event_ms - {widest} and "
            "t.event_ms\n"
            ")",
            f"card_windows as (\n    select\n        transaction_id,\n        {select}\n"
            "    from card_pairs\n    group by transaction_id\n)",
        ]

    def previous(self) -> list[str]:
        filters = sorted(
            {
                str(f.filter)
                for f in self.by_kind("card", "distance_from_previous", "minutes_since_previous")
            }
        )
        ctes = []
        for i, flt in enumerate(filters):
            over = "over (partition by card_id order by event_ms, arrival)"
            ctes.append(
                f"previous_{i} as (\n"
                "    -- latest earlier transaction by event time, ties by arrival order\n"
                "    select\n        transaction_id,\n"
                f"        event_ms - lag(event_ms) {over} as gap_ms,\n"
                f"        lag(lat) {over} as prev_lat,\n"
                f"        lag(lon) {over} as prev_lon,\n"
                "        lat, lon\n"
                f"    from txn\n    where {flt}\n)"
            )
        return ctes

    def merchant_windows(self) -> list[str]:
        ctes = []
        for f in self.by_kind("merchant", "status_rate"):
            w = window_ms(f)
            ctes.append(
                f"{f.name}__events as (\n"
                "    select merchant_id, event_ms as at_ms, 1 as created, 0 as changed from txn\n"
                "    union all\n"
                f"    select merchant_id, status_ms, 0, 1 from txn\n"
                f"    where status = '{f.status}' and status_ms is not null\n"
                ")"
            )
            ctes.append(
                f"{f.name}__w as (\n"
                "    select t.transaction_id, sum(e.created) as n_created, sum(e.changed) as "
                "n_changed\n"
                "    from txn as t\n"
                f"    inner join {f.name}__events as e\n"
                f"        on t.merchant_id = e.merchant_id and e.at_ms between t.event_ms - {w} "
                "and t.event_ms\n"
                "    group by t.transaction_id\n)"
            )
        return ctes

    def customer(self) -> list[str]:
        ctes = []
        devices = self.by_kind("customer", "first_seen_within")
        if devices:
            ctes.append(
                "sessions as (\n"
                f"    select session_id, customer_id, device_id, {epoch_ms('event_ts')} as "
                "event_ms\n"
                "    from {{ ref('sessions_current') }}\n    where not is_deleted\n)"
            )
            ctes.append(
                "first_seen as (\n"
                "    select customer_id, device_id, min(event_ms) as first_ms\n"
                "    from sessions\n    group by customer_id, device_id\n)"
            )
            for f in devices:
                w = window_ms(f)
                ctes.append(
                    f"{f.name}__v as (\n"
                    "    select\n        t.transaction_id,\n"
                    "        case when s.session_id is null then null\n"
                    f"            else fs.first_ms between t.event_ms - {w} and t.event_ms end as "
                    "v\n"
                    "    from txn as t\n"
                    "    left join sessions as s on t.session_id = s.session_id\n"
                    "    left join first_seen as fs\n"
                    "        on s.customer_id = fs.customer_id and s.device_id = fs.device_id\n)"
                )
        changes = self.by_kind("customer", "changed_within")
        if changes:
            ctes.append(
                "owners as (\n    select card_id, customer_id\n"
                "    from {{ ref('cards_current') }}\n    where not is_deleted\n)"
            )
        for f in changes:
            cols = list(f.columns)
            lags = ",\n".join(
                f"        lag({c}) over (partition by customer_id order by _kafka_offset) as "
                f"prev_{c}"
                for c in cols
            )
            changed = " or ".join(f"{c} is distinct from prev_{c}" for c in cols)
            w = window_ms(f)
            ctes.append(
                f"{f.name}__events as (\n"
                "    select\n        customer_id, _op,\n"
                f"        {epoch_ms('event_ts')} as event_ms,\n"
                + "".join(f"        {c},\n" for c in cols)
                + "        lag(_kafka_offset) over "
                "(partition by customer_id order by _kafka_offset) as prev_offset,\n"
                f"{lags}\n"
                "    from {{ ref('stg_cdc__customers') }}\n)"
            )
            ctes.append(
                f"{f.name}__changes as (\n"
                "    -- an update whose watched columns differ from the customer's previous event\n"
                f"    select customer_id, event_ms from {f.name}__events\n"
                f"    where _op = 'u' and prev_offset is not null and ({changed})\n)"
            )
            ctes.append(
                f"{f.name}__v as (\n"
                "    select t.transaction_id, o.customer_id, count(c.event_ms) as n\n"
                "    from txn as t\n"
                "    left join owners as o on t.card_id = o.card_id\n"
                f"    left join {f.name}__changes as c\n"
                "        on o.customer_id = c.customer_id and c.event_ms between t.event_ms - "
                f"{w} and t.event_ms\n"
                "    group by t.transaction_id, o.customer_id\n)"
            )
        return ctes

    # ------------------------------------------------------------------ assembly

    def expression(self, f: Feature) -> str:
        prev_index = sorted(
            {
                str(x.filter)
                for x in self.by_kind("card", "distance_from_previous", "minutes_since_previous")
            }
        )
        if f.kind in ("window_count", "window_sum", "window_count_distinct"):
            return f"cw.{f.name}"
        if f.kind == "ratio_to_prior_mean":
            return f"cast(t.{f.field} as double) / cw.{f.name}__mean"
        if f.kind == "minutes_since_previous":
            # Trino reads 60000.0 as DECIMAL and would round the quotient: divide doubles.
            return f"cast(p{prev_index.index(str(f.filter))}.gap_ms as double) / 60000"
        if f.kind == "distance_from_previous":
            p = f"p{prev_index.index(str(f.filter))}"
            return (
                f"2 * {EARTH_RADIUS_KM} * asin(sqrt(\n"
                f"            power(sin(radians({p}.lat - {p}.prev_lat) / 2), 2)\n"
                f"            + cos(radians({p}.prev_lat)) * cos(radians({p}.lat))\n"
                f"            * power(sin(radians({p}.lon - {p}.prev_lon) / 2), 2)\n        ))"
            )
        if f.kind == "status_rate":
            return f"cast({f.name}__w.n_changed as double) / {f.name}__w.n_created"
        if f.kind == "first_seen_within":
            return f"{f.name}__v.v"
        if f.kind == "changed_within":
            return (
                f"case when {f.name}__v.customer_id is null then null "
                f"else {f.name}__v.n > 0 end"
            )
        raise NotImplementedError(f"{f.name}: kind {f.kind}")

    def joins(self) -> list[str]:
        out = []
        if self.card_windows():
            out.append("left join card_windows as cw on t.transaction_id = cw.transaction_id")
        for i, _ in enumerate(self.previous()):
            out.append(f"left join previous_{i} as p{i} on t.transaction_id = p{i}.transaction_id")
        for f in self.by_kind("merchant", "status_rate"):
            out.append(f"left join {f.name}__w on t.transaction_id = {f.name}__w.transaction_id")
        for f in self.by_kind("customer", "first_seen_within", "changed_within"):
            out.append(f"left join {f.name}__v on t.transaction_id = {f.name}__v.transaction_id")
        return out

    def sql(self) -> str:
        ctes = (
            self.base()
            + self.card_windows()
            + self.previous()
            + self.merchant_windows()
            + self.customer()
        )
        cols = ",\n    ".join(
            f"cast({self.expression(f)} as {f.dtype}) as {f.name}" for f in self.defs.features
        )
        return (
            HEADER
            + "\n-- Offline features (FR-PAR1): every feature for every transaction, as of its\n"
            "-- event time, recomputed from the lake with the same definitions as Flink and the\n"
            "-- decision service. Parity (FR-PAR2) compares them with what each decision logged.\n"
            "with " + ",\n\n".join(ctes) + "\n\n"
            "select\n    t.transaction_id,\n    t.card_id,\n    t.merchant_id,\n    t.event_ms,\n"
            f"    {cols},\n    {self.defs.version} as definitions_version\n"
            "from txn as t\n" + "\n".join(self.joins()) + "\n"
        )
