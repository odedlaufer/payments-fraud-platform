"""Renders docs/feature-catalogue.md from the definitions."""

from features.model import Definitions

HEADER = "<!-- Generated by `uv run features catalogue` from features/definitions.yml. -->\n"


def render(defs: Definitions) -> str:
    lines = [
        HEADER,
        "# Feature catalogue",
        "",
        f"Definitions version {defs.version}. Every feature is computed online by Flink and "
        "offline by dbt from the same definition (ADR-003).",
        "",
        "## Semantics",
        "",
        "| Rule | Value |",
        "| --- | --- |",
    ]
    lines += [f"| {key} | `{value}` |" for key, value in defs.semantics.items()]
    for entity, key in defs.entities.items():
        features = defs.for_entity(entity)
        if not features:
            continue
        lines += [
            "",
            f"## {entity.capitalize()} features (key `{key}`)",
            "",
            "| Feature | Kind | Window | Type | Version | Definition |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        lines += [
            f"| `{f.name}` | {f.kind} | {f.window or '-'} | {f.dtype} | {f.version} | "
            f"{f.description} |"
            for f in features
        ]
    return "\n".join(lines) + "\n"
