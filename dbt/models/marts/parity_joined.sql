-- One row per decision (the latest per transaction), with its logged snapshot
-- and the offline features recomputed from the lake (input to parity_comparisons).
with decisions as (
    select
        transaction_id, decision, reason, definitions_version, features, decided_at,
        row_number() over (partition by transaction_id order by kafka_offset desc) as rn
    from {{ source('decision_log', 'decisions') }}
)

select
    d.transaction_id, d.decision, d.reason, d.decided_at,
    d.definitions_version as logged_version,
    d.features as f,
    o.card_id, o.merchant_id, o.event_ms,
    cast(t.event_ts as date) as event_day,
    o.txn_count_1m as o_txn_count_1m,
    o.txn_count_1h as o_txn_count_1h,
    o.txn_count_24h as o_txn_count_24h,
    o.txn_amount_sum_1h as o_txn_amount_sum_1h,
    o.txn_amount_sum_24h as o_txn_amount_sum_24h,
    o.distinct_merchants_1h as o_distinct_merchants_1h,
    o.amount_vs_avg_30d as o_amount_vs_avg_30d,
    o.km_from_last_txn as o_km_from_last_txn,
    o.minutes_since_last_txn as o_minutes_since_last_txn,
    o.new_device_24h as o_new_device_24h,
    o.profile_change_24h as o_profile_change_24h,
    o.merchant_refund_rate_7d as o_merchant_refund_rate_7d,
    (d.features.txn_count_1m is not null or d.features.txn_count_1h is not null or d.features.txn_count_24h is not null or d.features.txn_amount_sum_1h is not null or d.features.txn_amount_sum_24h is not null or d.features.distinct_merchants_1h is not null or d.features.amount_vs_avg_30d is not null or d.features.km_from_last_txn is not null or d.features.minutes_since_last_txn is not null) as card_logged,
    (d.features.new_device_24h is not null or d.features.profile_change_24h is not null) as customer_logged,
    (d.features.merchant_refund_rate_7d is not null) as merchant_logged
from decisions as d
inner join {{ ref('card_offline') }} as o on d.transaction_id = o.transaction_id
inner join {{ ref('transactions_current') }} as t on d.transaction_id = t.transaction_id
where d.rn = 1
