-- Offline features (FR-PAR1): every feature for every transaction, as of its
-- event time, recomputed from the lake with the same definitions as Flink and the
-- decision service. Parity (FR-PAR2) compares them with what each decision logged.
with created as (
    -- arrival order: the offset of each transaction's creation event
    select transaction_id, min(_kafka_offset) as arrival
    from {{ ref('stg_cdc__transactions') }}
    where _op in ('c', 'r')
    group by transaction_id
),

txn as (
    select
        t.transaction_id, t.card_id, t.merchant_id, t.session_id, t.amount,
        t.channel, t.lat, t.lon, t.status, c.arrival,
        {{ epoch_ms('t.event_ts') }} as event_ms,
        {{ epoch_ms('t.status_event_ts') }} as status_ms
    from {{ ref('transactions_current') }} as t
    inner join created as c on t.transaction_id = c.transaction_id
    where not t.is_deleted
),

card_pairs as (
    select t.transaction_id, o.transaction_id as other_id, o.amount as o_amount, o.merchant_id as o_merchant_id,
        t.event_ms - o.event_ms as age_ms
    from txn as t
    inner join txn as o
        on t.card_id = o.card_id and o.event_ms between t.event_ms - 2592000000 and t.event_ms
),

card_windows as (
    select
        transaction_id,
        count_if(age_ms <= 60000) as txn_count_1m,
        count_if(age_ms <= 3600000) as txn_count_1h,
        count_if(age_ms <= 86400000) as txn_count_24h,
        cast(sum(case when age_ms <= 3600000 then o_amount else 0 end) as decimal(18,2)) as txn_amount_sum_1h,
        cast(sum(case when age_ms <= 86400000 then o_amount else 0 end) as decimal(18,2)) as txn_amount_sum_24h,
        count(distinct case when age_ms <= 3600000 then o_merchant_id end) as distinct_merchants_1h,
        avg(case when age_ms <= 2592000000 and other_id != transaction_id then cast(o_amount as double) end) as amount_vs_avg_30d__mean
    from card_pairs
    group by transaction_id
),

previous_0 as (
    -- latest earlier transaction by event time, ties by arrival order
    select
        transaction_id,
        event_ms - lag(event_ms) over (partition by card_id order by event_ms, arrival) as gap_ms,
        lag(lat) over (partition by card_id order by event_ms, arrival) as prev_lat,
        lag(lon) over (partition by card_id order by event_ms, arrival) as prev_lon,
        lat, lon
    from txn
    where channel = 'card_present'
),

merchant_refund_rate_7d__events as (
    select merchant_id, event_ms as at_ms, 1 as created, 0 as changed from txn
    union all
    select merchant_id, status_ms, 0, 1 from txn
    where status = 'reversed' and status_ms is not null
),

merchant_refund_rate_7d__w as (
    select t.transaction_id, sum(e.created) as n_created, sum(e.changed) as n_changed
    from txn as t
    inner join merchant_refund_rate_7d__events as e
        on t.merchant_id = e.merchant_id and e.at_ms between t.event_ms - 604800000 and t.event_ms
    group by t.transaction_id
),

sessions as (
    select session_id, customer_id, device_id, {{ epoch_ms('event_ts') }} as event_ms
    from {{ ref('sessions_current') }}
    where not is_deleted
),

first_seen as (
    select customer_id, device_id, min(event_ms) as first_ms
    from sessions
    group by customer_id, device_id
),

new_device_24h__v as (
    select
        t.transaction_id,
        case when s.session_id is null then null
            else fs.first_ms between t.event_ms - 86400000 and t.event_ms end as v
    from txn as t
    left join sessions as s on t.session_id = s.session_id
    left join first_seen as fs
        on s.customer_id = fs.customer_id and s.device_id = fs.device_id
),

owners as (
    select card_id, customer_id
    from {{ ref('cards_current') }}
    where not is_deleted
),

profile_change_24h__events as (
    select
        customer_id, _op,
        {{ epoch_ms('event_ts') }} as event_ms,
        email,
        phone,
        address_line,
        lag(_kafka_offset) over (partition by customer_id order by _kafka_offset) as prev_offset,
        lag(email) over (partition by customer_id order by _kafka_offset) as prev_email,
        lag(phone) over (partition by customer_id order by _kafka_offset) as prev_phone,
        lag(address_line) over (partition by customer_id order by _kafka_offset) as prev_address_line
    from {{ ref('stg_cdc__customers') }}
),

profile_change_24h__changes as (
    -- an update whose watched columns differ from the customer's previous event
    select customer_id, event_ms from profile_change_24h__events
    where _op = 'u' and prev_offset is not null and (email is distinct from prev_email or phone is distinct from prev_phone or address_line is distinct from prev_address_line)
),

profile_change_24h__v as (
    select t.transaction_id, o.customer_id, count(c.event_ms) as n
    from txn as t
    left join owners as o on t.card_id = o.card_id
    left join profile_change_24h__changes as c
        on o.customer_id = c.customer_id and c.event_ms between t.event_ms - 86400000 and t.event_ms
    group by t.transaction_id, o.customer_id
)

select
    t.transaction_id,
    t.card_id,
    t.merchant_id,
    t.event_ms,
    cast(cw.txn_count_1m as bigint) as txn_count_1m,
    cast(cw.txn_count_1h as bigint) as txn_count_1h,
    cast(cw.txn_count_24h as bigint) as txn_count_24h,
    cast(cw.txn_amount_sum_1h as decimal(18,2)) as txn_amount_sum_1h,
    cast(cw.txn_amount_sum_24h as decimal(18,2)) as txn_amount_sum_24h,
    cast(cw.distinct_merchants_1h as bigint) as distinct_merchants_1h,
    cast(cast(t.amount as double) / cw.amount_vs_avg_30d__mean as double) as amount_vs_avg_30d,
    cast(2 * 6371.0088 * asin(sqrt(
            power(sin(radians(p0.lat - p0.prev_lat) / 2), 2)
            + cos(radians(p0.prev_lat)) * cos(radians(p0.lat))
            * power(sin(radians(p0.lon - p0.prev_lon) / 2), 2)
        )) as double) as km_from_last_txn,
    cast(cast(p0.gap_ms as double) / 60000 as double) as minutes_since_last_txn,
    cast(new_device_24h__v.v as boolean) as new_device_24h,
    cast(case when profile_change_24h__v.customer_id is null then null else profile_change_24h__v.n > 0 end as boolean) as profile_change_24h,
    cast(cast(merchant_refund_rate_7d__w.n_changed as double) / merchant_refund_rate_7d__w.n_created as double) as merchant_refund_rate_7d,
    1 as definitions_version
from txn as t
left join card_windows as cw on t.transaction_id = cw.transaction_id
left join previous_0 as p0 on t.transaction_id = p0.transaction_id
left join merchant_refund_rate_7d__w on t.transaction_id = merchant_refund_rate_7d__w.transaction_id
left join new_device_24h__v on t.transaction_id = new_device_24h__v.transaction_id
left join profile_change_24h__v on t.transaction_id = profile_change_24h__v.transaction_id
