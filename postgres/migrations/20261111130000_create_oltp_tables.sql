-- Real wall-clock time of the last change. event_ts on each row is the
-- simulator's accelerated clock; commit time comes from CDC (source.ts_ms).
create function public.set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

create table public.customers (
    customer_id bigint generated by default as identity primary key,
    full_name text not null,
    email text not null,
    phone text not null,
    address_line text not null,
    city text not null,
    country_code char(2) not null,
    home_lat double precision not null,
    home_lon double precision not null,
    risk_tier text not null default 'low',
    event_ts timestamptz not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint customers_risk_tier_valid check (risk_tier in ('low', 'medium', 'high'))
);

create table public.cards (
    card_id bigint generated by default as identity primary key,
    customer_id bigint not null references public.customers (customer_id),
    pan_last4 char(4) not null check (pan_last4 ~ '^[0-9]{4}$'),
    card_type text not null check (card_type in ('credit', 'debit')),
    status text not null default 'active',
    credit_limit numeric(12, 2) not null check (credit_limit >= 0),
    expires_on date not null,
    event_ts timestamptz not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint cards_status_valid check (status in ('active', 'blocked', 'expired'))
);

create table public.merchants (
    merchant_id bigint generated by default as identity primary key,
    name text not null,
    mcc char(4) not null check (mcc ~ '^[0-9]{4}$'),
    category text not null,
    country_code char(2) not null,
    lat double precision not null,
    lon double precision not null,
    status text not null default 'active',
    event_ts timestamptz not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint merchants_status_valid check (status in ('active', 'suspended'))
);

create table public.sessions (
    session_id bigint generated by default as identity primary key,
    customer_id bigint not null references public.customers (customer_id),
    device_id text not null,
    ip_address inet not null,
    ip_country char(2) not null,
    event_ts timestamptz not null,
    created_at timestamptz not null default now()
);

-- merchant_id has no foreign key on purpose: merchants are hard-deleted
-- (FR-SIM5), and their transactions must survive. History lives in the lakehouse.
create table public.transactions (
    transaction_id bigint generated by default as identity primary key,
    card_id bigint not null references public.cards (card_id),
    merchant_id bigint not null,
    session_id bigint references public.sessions (session_id),
    amount numeric(12, 2) not null check (amount > 0),
    currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
    channel text not null check (channel in ('card_present', 'online')),
    status text not null default 'pending',
    lat double precision,
    lon double precision,
    event_ts timestamptz not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint transactions_status_valid check (
        status in ('pending', 'approved', 'declined', 'reversed')
    ),
    constraint transactions_card_present_has_location check (
        channel <> 'card_present' or (lat is not null and lon is not null)
    )
);

create table public.chargebacks (
    chargeback_id bigint generated by default as identity primary key,
    transaction_id bigint not null unique references public.transactions (transaction_id),
    reason_code text not null,
    amount numeric(12, 2) not null check (amount > 0),
    event_ts timestamptz not null,
    created_at timestamptz not null default now()
);

create index cards_customer_id_idx on public.cards (customer_id);
create index sessions_customer_id_idx on public.sessions (customer_id);
create index transactions_card_id_idx on public.transactions (card_id);
create index transactions_merchant_id_idx on public.transactions (merchant_id);
create index transactions_session_id_idx on public.transactions (session_id);

create trigger customers_set_updated_at before update on public.customers
for each row execute function public.set_updated_at();
create trigger cards_set_updated_at before update on public.cards
for each row execute function public.set_updated_at();
create trigger merchants_set_updated_at before update on public.merchants
for each row execute function public.set_updated_at();
create trigger transactions_set_updated_at before update on public.transactions
for each row execute function public.set_updated_at();

